"""Pulls the main site's nav, footer links and base styles into this app.

shoemakerc.github.io publishes them at /shared/site.json and /shared/base.css
so its side projects can wear the same header, footer and type. This saves
them as dance_judge/site.json and dance_judge/static/site-base.css. Both are
committed, so if the site can't be reached the last copy is used.

Run it before a deploy (render.yaml does), or by hand:

    python scripts/sync_site.py

SITE_URL points at another copy of the site, e.g. a local dev server.
"""

import json
import os
import time
import urllib.request
from pathlib import Path

SITE_URL = os.environ.get("SITE_URL", "https://shoemakerc.github.io").rstrip("/")
PACKAGE = Path(__file__).resolve().parent.parent / "dance_judge"


def get(name: str) -> str:
    # The query string skips GitHub Pages' cache, so a fresh deploy shows up.
    with urllib.request.urlopen(f"{SITE_URL}/shared/{name}?t={int(time.time())}", timeout=10) as res:
        return res.read().decode("utf-8")


try:
    shared = json.loads(get("site.json"))
    css = get("base.css")
    if not all(key in shared for key in ("name", "url", "nav", "links")):
        raise ValueError("site.json is missing name, url, nav or links")
    (PACKAGE / "site.json").write_text(json.dumps(shared, indent=2, ensure_ascii=False) + "\n")
    (PACKAGE / "static" / "site-base.css").write_text(
        f"/* Generated by scripts/sync_site.py from {SITE_URL}/shared/base.css. Don't edit. */\n\n{css}"
    )
    print(f"Synced nav, links and base styles from {SITE_URL}")
except Exception as error:  # noqa: BLE001 - any failure falls back to the saved copy
    print(f"Couldn't sync from {SITE_URL} ({error}); using the saved copy.")
